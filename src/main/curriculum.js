/* ------------------------------------------------------------------ *
 * 取色：让同一个领域下的课程是「一家人」，但彼此能区分
 * ------------------------------------------------------------------ */

function hexToHsl(hex) {
  const m = /^#?([0-9a-f]{6})$/i.exec(String(hex));
  if (!m) return { h: 220, s: 70, l: 45 };
  const n = parseInt(m[1], 16);
  const r = ((n >> 16) & 255) / 255, g = ((n >> 8) & 255) / 255, b = (n & 255) / 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  const l = (max + min) / 2;
  if (max === min) return { h: 0, s: 0, l: l * 100 };
  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  let h;
  if (max === r) h = ((g - b) / d + (g < b ? 6 : 0)) / 6;
  else if (max === g) h = ((b - r) / d + 2) / 6;
  else h = ((r - g) / d + 4) / 6;
  return { h: h * 360, s: s * 100, l: l * 100 };
}

function hslToHex(h, s, l) {
  const S = s / 100, L = l / 100;
  const c = (1 - Math.abs(2 * L - 1)) * S;
  const hp = (((h % 360) + 360) % 360) / 60;
  const x = c * (1 - Math.abs((hp % 2) - 1));
  let r = 0, g = 0, b = 0;
  if (hp < 1) { r = c; g = x; } else if (hp < 2) { r = x; g = c; }
  else if (hp < 3) { g = c; b = x; } else if (hp < 4) { g = x; b = c; }
  else if (hp < 5) { r = x; b = c; } else { r = c; b = x; }
  const m = L - c / 2;
  const to = (v) => Math.round((v + m) * 255).toString(16).padStart(2, '0');
  return '#' + to(r) + to(g) + to(b);
}

/**
 * 第 i 门课的颜色。
 * 围绕领域主色做小幅色相偏移 + 明度阶梯：同一个空间里一眼能看出「这是一家人」，
 * 又能把每条曲线、每个扇形分清楚。直接全部用同一个颜色会让图表彻底失去可读性。
 */
function tint(base, i, n) {
  const { h, s, l } = hexToHsl(base);
  const spread = n <= 1 ? 0 : 34;
  const dh = ((i - (n - 1) / 2) / Math.max(1, n - 1)) * spread;
  const dl = (i % 2 ? 7 : 0) + Math.floor(i / 3) * 6;
  return hslToHex(h + dh, Math.min(78, Math.max(38, s - (i % 3) * 7)), Math.min(58, Math.max(30, l - 6 + dl)));
}

